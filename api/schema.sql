create table if not exists public.indicators (
  id bigint generated by default as identity primary key,
  period text not null,
  indicator_key text not null,
  indicator text not null,
  value double precision not null,
  unit text not null,
  category text not null,
  source text not null,
  source_url text not null,
  status text not null default 'unverified',
  updated_at timestamptz not null default now(),
  unique(period, indicator_key, source)
);
create index if not exists indicators_category_idx on public.indicators(category);
create index if not exists indicators_period_idx on public.indicators(period);
create table if not exists public.research_history (
  id bigint generated by default as identity primary key,
  question text not null,
  answer text not null,
  sources jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);
-- Access should go through the backend using DATABASE_URL. Do not expose service-role keys in browser code.
alter table public.indicators enable row level security;
alter table public.research_history enable row level security;
